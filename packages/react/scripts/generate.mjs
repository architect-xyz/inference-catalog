// Reads the catalog at the repository root and writes src/generated/:
//   logos/<ns>/<id>.ts  one module for each logo, whose default export is a data URI
//   catalog.ts          the creators, providers and harnesses, and the loader of each logo
//   rules.ts            the rules that pick a logo for a model name
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { ROOT, readEntities, readJson, readLogos } from '../../../scripts/lib.mjs'

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/generated')
rmSync(out, { recursive: true, force: true })

const logos = readLogos()
for (const logo of logos) {
  const data = readFileSync(join(ROOT, logo.file)).toString('base64')
  const path = join(out, 'logos', `${logo.ref}.ts`)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, `export default 'data:${logo.mime};base64,${data}'\n`)
}

const pick = (entities, fields) =>
  Object.fromEntries(entities.map(({ value }) => [value.id, Object.fromEntries(fields.map((f) => [f, value[f] ?? null]))]))

const creators = pick(readEntities('creators'), ['name', 'aliases', 'logo'])
const providers = pick(readEntities('providers'), ['name', 'type', 'logo'])
const harnesses = pick(readEntities('harnesses'), ['name', 'logo'])

const loaders = logos.map((l) => `  '${l.ref}': () => import('./logos/${l.ref}'),`).join('\n')
writeFileSync(
  join(out, 'catalog.ts'),
  `// Generated by scripts/generate.mjs. Do not edit.
export const CREATORS: Record<string, { name: string; aliases: string[]; logo: string | null }> = ${JSON.stringify(creators)}
export const PROVIDERS: Record<string, { name: string; type: string; logo: string | null }> = ${JSON.stringify(providers)}
export const HARNESSES: Record<string, { name: string; logo: string | null }> = ${JSON.stringify(harnesses)}
export const LOGO_LOADERS: Record<string, () => Promise<{ default: string }>> = {
${loaders}
}
`
)

const rules = readJson(join(ROOT, 'rules/model-logos.json'))
writeFileSync(
  join(out, 'rules.ts'),
  `// Generated by scripts/generate.mjs. Do not edit.
export const MODEL_LOGO_RULES: {
  exact: Record<string, string>
  families: Record<string, string>
  familyAliases: Record<string, string>
  fallback: string
} = ${JSON.stringify({ exact: rules.exact, families: rules.families, familyAliases: rules.familyAliases, fallback: rules.fallback })}
`
)
console.log(`generated ${logos.length} logo modules`)
